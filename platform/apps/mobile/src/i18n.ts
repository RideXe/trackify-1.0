export const languages = [
  { code: 'en', label: 'English' },
  { code: 'kn', label: 'ಕನ್ನಡ' },
  { code: 'hi', label: 'हिन्दी' },
  { code: 'ta', label: 'தமிழ்' },
] as const;
export type Language = (typeof languages)[number]['code'];

const tables: Record<Language, Strings> = { en, kn, hi, ta };
/** For tests only. */
export const stringTables = tables;
const languageKey = 'driver-language-v1';
let current: Language = 'en';
const listeners = new Set<() => void>();

export function translate(
  language: Language,
  key: StringKey,
  values: Record<string, string | number> = {},
): string {
  const template = tables[language][key] ?? en[key];
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in values ? String(values[name]) : match,
  );
}

export async function loadLanguage() {
  const saved = await SecureStore.getItemAsync(languageKey).catch(() => null);
  if (saved && saved in tables) setCurrent(saved as Language);
}

export async function chooseLanguage(language: Language) {
  setCurrent(language);
  await SecureStore.setItemAsync(languageKey, language);
}

function setCurrent(language: Language) {
  current = language;
  for (const listener of listeners) listener();
}

/** The chosen language and a translator bound to it; components re-render when it changes. */
export function useStrings() {
  const language = useSyncExternalStore(
    (listener) => {
      listeners.add(listener);
      return () => listeners.delete(listener);
    },
    () => current,
  );
  return {
    language,
    t: (key: StringKey, values?: Record<string, string | number>) =>
      translate(language, key, values),
  };
}
